const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const result = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(__dirname + '/src/nativePlayback.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:result});
const parse = result.nativePlaybackRequest;
const message = values => JSON.stringify({type:'native-play',id:'movie:example',title:'Test',url:'http://127.0.0.1:11470/abcd/1',position:30,...values});
assert.equal(parse(message({})).position, 30);
assert.equal(parse(message({position:-5})).position, 0);
assert.equal(parse(message({position:'30'})).position, 0);
assert.equal(parse(message({url:'file:///etc/passwd'})), null);
assert.equal(parse(message({url:'javascript:alert(1)'})), null);
assert.equal(parse(message({type:'other'})), null);
assert.equal(parse('bad json'), null);
assert.equal(parse('x'.repeat(20001)), null);
assert.equal(parse(message({hash:'not-a-hash'})).hash, undefined);
assert.equal(parse(message({seeders:0})).seeders, 0);
assert.equal(parse(message({leechers:-1})).leechers, null);
assert.equal(result.isBundledPage(undefined), false);
assert.equal(result.isBundledPage('https://example.org/app/'), false);
assert.equal(result.isBundledPage('http://127.0.0.1:11470/app/#/tv/sources'), true);
console.log('14 native playback bridge checks passed');
